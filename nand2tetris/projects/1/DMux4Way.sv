/**
 * 4-way demultiplexor:
 * [a, b, c, d] = [in, 0, 0, 0] if sel = 00
 *                [0, in, 0, 0] if sel = 01
 *                [0, 0, in, 0] if sel = 10
 *                [0, 0, 0, in] if sel = 11
 */
module DMux4Way(
    input logic in,
    input logic [1:0] sel,
    output logic a,
    output logic b,
    output logic c,
    output logic d
);

endmodule
